#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""导出 U3 区域的「小分子–靶点复合物」结构文件

  results/U3_complex_LGR5_formononetin.pdb   受体(A 链胞外域) + 芒柄花素 U3 最佳姿态
  results/U3_ligand_only.pdb                 仅配体姿态（便于单独载入）

姿态选取：盲对接轮（blind_apo_e128）中，配体质心距 U3 区域中心 ≤5 Å 者，取 CNNscore 最高
          —— 与 u3_analysis.py 完全同一判据，可复算。
配体以 HETATM 记录写出，残基名 LIG、链 L、序号 1。
"""
from config import ROOT, HERE, path, CFG   # 路径全部来自 config.yaml，禁止硬编码
import gzip
import os

import numpy as np
from rdkit import Chem
from rdkit import RDLogger
RDLogger.DisableLog('rdApp.*')

BASE = ROOT
REC = os.path.join(BASE, 'data', 'receptor_apo_LGR5.pdb')
SRC = os.path.join(BASE, 'results', 'blind_apo_e128.sdf.gz')
OUT_C = os.path.join(BASE, 'results', 'U3_complex_LGR5_formononetin.pdb')
OUT_L = os.path.join(BASE, 'results', 'U3_ligand_only.pdb')
CEN = np.array([25.17, -17.39, 41.21])       # U3 质心（来自 unified_sites.tsv）
CLUSTER = 5.0

# ---------- 选姿态 ----------
best = None
with gzip.open(SRC, 'rb') as fh:
    supp = Chem.ForwardSDMolSupplier(fh, removeHs=False, sanitize=False)
    for m in supp:
        if m is None:
            continue
        conf = m.GetConformer()
        atoms = []
        for a in m.GetAtoms():
            if a.GetSymbol().upper() in ('H', 'D'):
                continue
            p = conf.GetAtomPosition(a.GetIdx())
            atoms.append((a.GetSymbol().upper(), np.array([p.x, p.y, p.z])))
        if not atoms:
            continue
        cen = np.mean([x for _, x in atoms], axis=0)
        if np.linalg.norm(cen - CEN) > CLUSTER:
            continue
        cnn = float(m.GetProp('CNNscore')) if m.HasProp('CNNscore') else float('nan')
        aff = (float(m.GetProp('minimizedAffinity'))
               if m.HasProp('minimizedAffinity') else float('nan'))
        if best is None or cnn > best['cnn']:
            best = {'cnn': cnn, 'aff': aff, 'atoms': atoms}
if best is None:
    raise SystemExit('ERROR: 未在 %s 中找到属于 U3 的姿态' % SRC)

print('选中姿态：CNNscore %.4f  affinity %.2f  kcal/mol  重原子 %d'
      % (best['cnn'], best['aff'], len(best['atoms'])))

# ---------- 写配体 ----------
ELEM2NAME = {'C': 'C', 'N': 'N', 'O': 'O', 'S': 'S', 'F': 'F', 'P': 'P'}
lig_lines = []
for i, (el, xyz) in enumerate(best['atoms'], 1):
    nm = ELEM2NAME.get(el, el)
    nm = ('%-3s' % nm)[:3]
    lig_lines.append(
        'HETATM%5d %-4s%1s%3s %1s%4d%1s   %8.3f%8.3f%8.3f%6.2f%6.2f'
        '          %2s  \n'
        % (i, nm, '', 'LIG', 'L', 1, '', xyz[0], xyz[1], xyz[2], 1.00, 0.00, el.rjust(2)))
with open(OUT_L, 'w', encoding='ascii') as f:
    f.writelines(lig_lines)
    f.write('TER\nEND\n')
print('已写出配体: %s' % OUT_L)

# ---------- 写复合物 ----------
n_rec = 0
with open(OUT_C, 'w', encoding='ascii') as f:
    f.write('REMARK   LGR5 (GPR49, UniProt O75473) ectodomain chain A  +  Formononetin (U3 site)\n')
    f.write('REMARK   receptor : data/receptor_apo_LGR5.pdb  (from RCSB 4KNG, chain A)\n')
    f.write('REMARK   ligand   : results/blind_apo_e128.sdf.gz, best-CNN pose within 5 A of U3 centroid\n')
    f.write('REMARK   ligand pose scores: CNNscore %.4f  minimizedAffinity %.2f kcal/mol\n'
            % (best['cnn'], best['aff']))
    f.write('REMARK   U3 centroid (%.2f, %.2f, %.2f); generated by export_u3_complex.py\n'
            % tuple(CEN))
    for l in open(REC, errors='replace'):
        if l.startswith(('ATOM', 'TER')):
            f.write(l)
            if l.startswith('ATOM'):
                n_rec += 1
    f.write('TER\n')
    f.writelines(lig_lines)
    f.write('TER\nEND\n')
print('已写出复合物: %s  （受体 %d 原子 + 配体 %d 原子）'
      % (OUT_C, n_rec, len(lig_lines)))
